export function countryName(country, lang) {
  if (!country) return null;
  if (lang === "en" || !LOCALES.includes(lang)) return country;
  return COUNTRIES[country]?.[lang] || country;
}

// --- plural helpers ---
const enp = (n, one, many) => (n === 1 ? one : many);
const etp = enp;
// Latvian: 1, 21, 31… take singular (but not 11).
const lvp = (n, one, many) => (n % 10 === 1 && n % 100 !== 11 ? one : many);
// Lithuanian: 1/21/31 singular; 2–9 (not 12–19) plural; rest genitive plural.
const ltp = (n, one, few, many) => {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 9 && (m100 < 11 || m100 > 19)) return few;
  return many;
};

